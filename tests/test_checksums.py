"""Unit tests for checksum-manifest parsing, writing, and calculation."""

import os
import tempfile
import unittest

from bwverify.checksums import (
    ChecksumFileError,
    ChecksumEntry,
    VerificationCancelled,
    calculate_checksum,
    calculate_crc32,
    manifest_comments_and_style,
    parse_checksum_file,
    parse_sfv_file,
    write_checksum_file,
)
from bwverify.document import load_document, save_new_document, save_open_document
from bwverify.settings import ApplicationSettings, load_settings, save_settings


# Temporary files make parser, writer, and calculation tests independent of the checkout.
class ChecksumTests(unittest.TestCase):
    """Exercise public checksum helpers with temporary files."""

    def write_file(self, directory, name, contents, binary=False):
        """Create a temporary text or binary file and return its path."""
        path = os.path.join(directory, name)
        mode = "wb" if binary else "w"
        with open(path, mode) as handle:
            handle.write(contents)
        return path

    def test_parses_comments_and_filenames_with_spaces(self):
        """SFV comments do not prevent filenames with leading spaces parsing."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(
                directory,
                "checks.sfv",
                "; Generated by bwVerify\n\n first file.bin abcdef12\nsecond.bin 00112233\n",
            )

            entries = parse_sfv_file(path)

        self.assertEqual(entries[0].filename, " first file.bin")
        self.assertEqual(entries[0].checksum, "ABCDEF12")
        self.assertEqual(entries[1].filename, "second.bin")

    def test_parses_hexadecimal_sfv_filenames_without_reversing_the_record(self):
        """An SFV filename may itself look like an eight-character checksum."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(directory, "checks.sfv", "a1b2c3d4 01234567\n")

            entries = parse_sfv_file(path)

        self.assertEqual(entries, [ChecksumEntry("a1b2c3d4", "01234567", "CRC-32")])

    def test_parses_gnu_text_and_binary_separators(self):
        """GNU text and binary records retain the filename after their separator."""
        digest = "900150983cd24fb0d6963f7d28e17f72"
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(
                directory,
                "checksums.md5",
                f"{digest}  text file.txt\n{digest} *binary file.txt\n",
            )

            entries = parse_checksum_file(path)

        self.assertEqual(entries[0], ChecksumEntry("text file.txt", digest.upper(), "MD5"))
        self.assertEqual(entries[1], ChecksumEntry("binary file.txt", digest.upper(), "MD5"))

    def test_rejects_invalid_records(self):
        """Malformed checksum records report a parsing error."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(directory, "checks.sfv", "not an SFV record\n")

            with self.assertRaises(ChecksumFileError):
                parse_sfv_file(path)

    def test_parses_gnu_md5_and_bsd_sha256_records(self):
        """GNU and BSD records can be combined in one manifest."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(
                directory,
                "checksums.txt",
                "900150983cd24fb0d6963f7d28e17f72  file.txt\n"
                "SHA256 (archive.tar) = "
                "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad\n",
            )

            entries = parse_checksum_file(path)

        self.assertEqual(entries[0].filename, "file.txt")
        self.assertEqual(entries[0].algorithm, "MD5")
        self.assertEqual(entries[1].filename, "archive.tar")
        self.assertEqual(entries[1].algorithm, "SHA-256")

    def test_parses_named_bsd_sha3_and_blake2_records(self):
        """Named BSD records select the algorithm rather than infer digest length."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(
                directory,
                "checksums.txt",
                "SHA3-256 (file.txt) = " + "a" * 64 + "\n"
                "BLAKE2b (archive.tar) = " + "b" * 128 + "\n",
            )

            entries = parse_checksum_file(path)

        self.assertEqual(entries[0].algorithm, "SHA3-256")
        self.assertEqual(entries[1].algorithm, "BLAKE2B")

