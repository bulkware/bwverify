    def test_calculates_crc32_in_streaming_chunks(self):
        """Streaming calculations return known CRC-32 and SHA-256 digests."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(directory, "file.bin", b"123456789", binary=True)

            self.assertEqual(calculate_crc32(path), "CBF43926")
            self.assertEqual(
                calculate_checksum(path, "SHA-256"),
                "15E2B0D3C33891EBB0F1EF609EC419420C20E320CE94C65FBC8C3312448EB225",
            )

    def test_stops_when_checksum_calculation_is_cancelled(self):
        """The cancellation callback stops a calculation before it completes."""
        with tempfile.TemporaryDirectory() as directory:
            path = self.write_file(directory, "file.bin", b"x" * 1024, binary=True)

            with self.assertRaises(VerificationCancelled):
                calculate_checksum(path, "SHA-256", lambda: True)

    def test_writes_and_reads_an_escaped_gnu_manifest(self):
        """GNU filename escaping survives a manifest write/read round trip."""
        with tempfile.TemporaryDirectory() as directory:
            source = self.write_file(directory, "file name.txt", b"abc", binary=True)
            manifest = os.path.join(directory, "checksums.sha256")
            entry = ChecksumEntry(
                "file\\name.txt", calculate_checksum(source, "SHA-256"), "SHA-256"
            )
            write_checksum_file(manifest, [entry])

            entries = parse_checksum_file(manifest)

        self.assertEqual(entries, [entry])

    def test_preserves_or_omits_comments_when_writing_a_manifest(self):
        """Comment retention is controlled by whether comments are supplied."""
        with tempfile.TemporaryDirectory() as directory:
            manifest = os.path.join(directory, "checks.sfv")
            entry = ChecksumEntry("file.bin", "CBF43926", "CRC-32")

            write_checksum_file(
                manifest, [entry], style="sfv", comments=["; created by test"]
            )
            comments, style = manifest_comments_and_style(manifest)
            self.assertEqual(comments, ["; created by test"])
            self.assertEqual(style, "sfv")

            write_checksum_file(manifest, [entry], style=style)
            comments, style = manifest_comments_and_style(manifest)
            self.assertEqual(comments, [])
            self.assertEqual(style, "sfv")

    def test_document_helpers_preserve_manifest_style_and_comments(self):
        """Document helpers keep metadata when an opened manifest is saved."""
        with tempfile.TemporaryDirectory() as directory:
            manifest = os.path.join(directory, "checks.sfv")
            write_checksum_file(
                manifest,
                [ChecksumEntry("file.bin", "CBF43926", "CRC-32")],
                style="sfv",
                comments=["; created by test"],
            )

            document = load_document(manifest)
            save_open_document(manifest, document.entries, document.style, document.comments)

            self.assertEqual(load_document(manifest), document)

    def test_document_helpers_apply_selected_encoding_and_line_endings(self):
        """New and opened manifests use the explicit output settings on every save."""
        with tempfile.TemporaryDirectory() as directory:
            manifest = os.path.join(directory, "checks.sfv")
            entry = ChecksumEntry("file.bin", "CBF43926", "CRC-32")

            save_open_document(
                manifest,
                [entry],
                "sfv",
                ["; comment"],
                encoding="utf-16",
                line_ending_identifier="crlf",
            )

            with open(manifest, "rb") as handle:
                contents = handle.read()
            self.assertTrue(contents.startswith((b"\xff\xfe", b"\xfe\xff")))
            self.assertIn("; comment\r\nfile.bin CBF43926\r\n", contents.decode("utf-16"))
            self.assertEqual(load_document(manifest).entries, [entry])

            save_new_document(
                manifest,
                [(os.path.join(directory, "file.bin"), "CBF43926", "CRC-32")],
                "sfv",
                encoding="latin-1",
                line_ending_identifier="cr",
            )
            with open(manifest, "rb") as handle:
                self.assertEqual(handle.read(), b"file.bin CBF43926\r")

    def test_new_document_writes_paths_relative_to_manifest(self):
        """New documents receive paths relative to their own output directory."""
        with tempfile.TemporaryDirectory() as directory:
            source_directory = os.path.join(directory, "source")
            os.mkdir(source_directory)
            source = self.write_file(source_directory, "file.bin", b"abc", binary=True)
            manifest = os.path.join(directory, "checksums.sha256")

            entries = save_new_document(
                manifest,
                [(source, calculate_checksum(source, "SHA-256"), "SHA-256")],
            )

            self.assertEqual(entries[0].filename, os.path.join("source", "file.bin"))
            self.assertEqual(load_document(manifest).entries, entries)

    def test_new_document_path_modes_control_stored_filenames(self):
        """New manifests can store relative, absolute, or basename-only filenames."""
        with tempfile.TemporaryDirectory() as directory:
            source_directory = os.path.join(directory, "source")
            os.mkdir(source_directory)
            source = self.write_file(source_directory, "file.bin", b"abc", binary=True)
            manifest = os.path.join(directory, "checksums.sfv")
            record = [(source, calculate_checksum(source, "CRC-32"), "CRC-32")]

            expected_filenames = {
                "relative": os.path.join("source", "file.bin"),
                "absolute": source,
                "filename": "file.bin",
            }
            for path_mode, expected_filename in expected_filenames.items():
                entries = save_new_document(manifest, record, "sfv", path_mode)
                self.assertEqual(entries[0].filename, expected_filename)
                self.assertEqual(load_document(manifest).entries, entries)

    def test_settings_round_trip_and_invalid_file_defaults(self):
        """Settings helpers retain valid values and safely fall back to defaults."""
        with tempfile.TemporaryDirectory() as directory:
            settings_path = os.path.join(directory, "config", "settings.conf")
            expected = ApplicationSettings(
                1024,
                768,
                directory,
                True,
                True,
                "bsd-sha256",
                "filename",
                "dark",
                "symbolic",
                "utf-16",
                "crlf",
            )
            save_settings(settings_path, expected)
            self.assertEqual(load_settings(settings_path), expected)

            with open(settings_path, "w", encoding="utf-8") as handle:
                handle.write("[preferences]\nicon_set = tango\n")
            self.assertEqual(load_settings(settings_path).icon_set, "tango")

            with open(settings_path, "w", encoding="utf-8") as handle:
                handle.write("[preferences]\nicon_set = unsupported\n")
            self.assertEqual(load_settings(settings_path).icon_set, "oxygen")

            with open(settings_path, "w", encoding="utf-8") as handle:
                handle.write(
                    "[preferences]\nfile_encoding = unsupported\nline_ending = unsupported\n"
                )
            values = load_settings(settings_path)
            self.assertEqual(values.file_encoding, "utf-8")
            self.assertEqual(values.line_ending, "lf")

            with open(settings_path, "w", encoding="utf-8") as handle:
                handle.write("[window]\nwidth = invalid\n")
            self.assertEqual(load_settings(settings_path), ApplicationSettings())

    def test_settings_loads_the_legacy_ini_file_when_conf_is_absent(self):
        """Renaming the settings file retains existing user preferences."""
        with tempfile.TemporaryDirectory() as directory:
            settings_path = os.path.join(directory, "config", "settings.conf")
            legacy_path = os.path.join(directory, "config", "settings.ini")
            expected = ApplicationSettings(theme="dark")

            save_settings(legacy_path, expected)

            self.assertEqual(load_settings(settings_path, legacy_path), expected)


